#!/usr/bin/env python3
"""Generates do-nothing definitions for functions the port does not provide.

Nintendo Wi-Fi Connection, local wireless (WM), the GBA slot, voice chat and
the microphone have no implementation in the port. The game still
links against them, so each gets a stub that does nothing and returns zero
(FALSE, NULL, "success" for SDK result codes).

The stubs use the exact prototypes from the headers the game includes: each
family of functions is preprocessed with the game's compiler flags and the
declaration of every missing symbol is copied from there.

Input is the linker's list of undefined symbols. Run tools/update_stubs.sh,
which links, collects the list and calls this script; it writes
game/stubs/<family>_stubs.c.

usage: gen_stubs.py <undefined.txt> <out dir> <cc> [cflags...]
"""
import re
import subprocess
import sys

FAMILIES = [
    ("net", "Nintendo Wi-Fi Connection, local wireless, GBA slot and voice chat",
     ["<nitro.h>", "<dwc.h>", "<gs/nonport.h>", "<nitroWiFi/soc.h>", "<ppwlobby/ppw_lobby.h>", "<vct.h>",
      '"nintendo_wfc/voice_chat.h"'],
     re.compile(r"^(DWC|PPW|SOC|WCM|WVR|WM|WMi|CTRDG|VoiceChat|B64)\w*$")),
    ("sound", "Sound functions the port does not provide",
     ['"sound.h"', '"sound_playback.h"', '"sound_chatot.h"', '"sound_system.h"'],
     re.compile(r"^(Sound\w*|sub_02005464)$")),
    ("sdk", "Other SDK functions",
     ["<nitro.h>"],
     re.compile(r".*")),
]


def preprocess(cc_cmd, includes):
    src = "".join(f"#include {inc}\n" for inc in includes)
    out = subprocess.run(cc_cmd + ["-E", "-x", "c", "-"], input=src, capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit(f"gen_stubs: preprocessing {includes} failed:\n{out.stderr[-3000:]}")
    text = "\n".join(line for line in out.stdout.splitlines() if not line.startswith("#"))
    return re.sub(r"\s+", " ", text)


def find_decl(text, sym):
    m = re.search(r"(?:^|[;}{])\s*([^;{}()]*?)\b" + re.escape(sym) + r"\s*\(([^;{}]*)\)\s*;", text)
    if not m:
        return None
    ret = re.sub(r"\b(extern|inline|static)\b", "", m.group(1))
    ret = re.sub(r"__attribute__\s*\(\(.*?\)\)", "", ret).strip()
    if not ret or "(" in ret or "=" in ret:
        return None
    return ret, m.group(2).strip()


def definition(sym, ret, params):
    if params == "":
        params = "void"
    head = f"{ret} {sym}({params})"
    if ret == "void":
        return f"{head}\n{{\n}}\n"
    return f"{head}\n{{\n    {ret} stubResult;\n    memset(&stubResult, 0, sizeof(stubResult));\n    return stubResult;\n}}\n"


def main():
    undefined_path, out_dir, cc_cmd = sys.argv[1], sys.argv[2], sys.argv[3:]
    symbols = sorted({line.split()[-1] for line in open(undefined_path) if line.strip()})
    pending = list(symbols)
    for name, title, includes, pattern in FAMILIES:
        mine = [s for s in pending if pattern.match(s)]
        if not mine:
            continue
        text = preprocess(cc_cmd, includes)
        defs = []
        for sym in mine:
            decl = find_decl(text, sym)
            if decl is None:
                continue
            defs.append(definition(sym, *decl))
            pending.remove(sym)
        if not defs:
            continue
        path = f"{out_dir}/{name}_stubs.c"
        with open(path, "w") as f:
            f.write(f"/*\n * {title}: stubs.\n *\n * Generated by tools/gen_stubs.py; do not edit. Functions that need real\n"
                    " * behaviour are implemented elsewhere, which removes them from this file.\n */\n")
            f.write("#include <string.h>\n\n")
            f.write("".join(f"#include {inc}\n" for inc in includes))
            f.write("\n" + "\n".join(defs))
        print(f"{path}: {len(defs)} stubs")
    if pending:
        # Called without a prototype in the decomp (implicit int functions).
        path = f"{out_dir}/implicit_stubs.c"
        with open(path, "w") as f:
            f.write("/*\n * Functions the game calls without a declaration (implicitly int), and\n"
                    " * that no source defines. Generated by tools/gen_stubs.py; do not edit.\n */\n\n")
            for sym in pending:
                f.write(f"int {sym}()\n{{\n    return 0;\n}}\n\n")
        print(f"{path}: {len(pending)} stubs ({' '.join(pending)})")


if __name__ == "__main__":
    main()
