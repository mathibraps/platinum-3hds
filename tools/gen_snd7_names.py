#!/usr/bin/env python3
"""Lists the ARM7 sound driver's symbols with an ARM7_ prefix.

The port builds NitroSDK's sound sources twice: for the ARM9 (the interface
the game calls) and for the ARM7 (the driver). Several sources serve both
CPUs, so both builds define the same names. This reads the symbols a first
compile of the ARM7 build defines (`nm -g -P` output on stdin) and writes a
header that renames each one (included by platform/include/ntr_snd7.h).

Usage: nm -g -P <ARM7 objects> | gen_snd7_names.py > ntr_snd7_names.h
"""
import re
import sys

names = set()
for line in sys.stdin:
    parts = line.split()
    # "name type [value size]"; file headers ("x.o:") have no type.
    if len(parts) < 2 or parts[0].endswith(":"):
        continue
    name, kind = parts[0], parts[1]
    if kind in "UvwN" or not re.match(r"^[A-Za-z]\w*$", name):
        continue
    names.add(name)

if not names:
    sys.exit("gen_snd7_names: no symbols on stdin")

out = ["/* Generated by tools/gen_snd7_names.py: the ARM7 sound driver's symbols. Do not edit. */",
       "#ifndef NTR_SND7_NAMES_H", "#define NTR_SND7_NAMES_H"]
out += [f"#define {n} ARM7_{n}" for n in sorted(names)]
out += ["#endif", ""]
sys.stdout.write("\n".join(out))
