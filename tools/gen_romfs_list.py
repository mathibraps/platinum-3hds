#!/usr/bin/env python3
"""Writes every file of the extracted ROM (romfs/) and its size as a C array,
sRomfsFiles, for the 3DS build's check of its ROM file system at start
(frontend/main_3ds.c). The header is only rewritten when the list changed.

usage: gen_romfs_list.py <romfs dir> <out.h>
"""
import os
import sys

root, out = sys.argv[1], sys.argv[2]
files = sorted(os.path.relpath(os.path.join(d, f), root) for d, _, fs in os.walk(root) for f in fs)
text = "/* Generated by tools/gen_romfs_list.py from %s/. */\n" % root
text += "static const struct { const char *path; u32 size; } sRomfsFiles[] = {\n"
text += "".join('    { "romfs:/%s", %d },\n' % (f, os.path.getsize(os.path.join(root, f))) for f in files) + "};\n"
if not os.path.exists(out) or open(out).read() != text:
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    open(out, "w").write(text)
