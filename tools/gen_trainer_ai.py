#!/usr/bin/env python3
"""Builds the trainer AI script table (src/battle/trainer_ai/script.s) as C.

The decomp assembles the script with arm-none-eabi-gcc. Here a host clang
assembles it for ARM, and the .text bytes (position independent: the script
only stores label distances) become a C array named gTrainerAITable.

usage: gen_trainer_ai.py <clang> <decomp> <decomp-gen> <out.c>
"""
import os
import struct
import subprocess
import sys
import tempfile


def text_section(elf):
    shoff = struct.unpack_from("<I", elf, 0x20)[0]
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", elf, 0x2E)
    sections = [struct.unpack_from("<IIIIIIIIII", elf, shoff + i * shentsize) for i in range(shnum)]
    strtab = sections[shstrndx]
    for sh in sections:
        name_off = strtab[4] + sh[0]
        name = elf[name_off:elf.index(b"\0", name_off)]
        if name == b".text":
            if any(s[1] in (9, 4) for s in sections):  # SHT_REL / SHT_RELA
                sys.exit("gen_trainer_ai: unexpected relocations in the script object")
            return elf[sh[4]:sh[4] + sh[5]]
    sys.exit("gen_trainer_ai: no .text section")


def main():
    clang, decomp, decomp_gen, out = sys.argv[1:5]
    src = os.path.join(decomp, "src/battle/trainer_ai/script.s")
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, "script.o")
        subprocess.run([clang, "--target=armv5te-none-eabi", "-x", "assembler-with-cpp",
                        "-I", os.path.join(decomp, "include"), "-I", os.path.join(decomp, "asm"),
                        "-I", decomp_gen, "-c", "-o", obj, src], check=True)
        data = text_section(open(obj, "rb").read())
    data += b"\0" * (-len(data) % 4)
    words = struct.unpack("<%dI" % (len(data) // 4), data)
    with open(out, "w") as f:
        f.write("/* Generated by tools/gen_trainer_ai.py from src/battle/trainer_ai/script.s. */\n")
        f.write("#include <stdint.h>\n\nuint32_t gTrainerAITable[%d] = {\n" % len(words))
        for i in range(0, len(words), 8):
            f.write("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    main()
