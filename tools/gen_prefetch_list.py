#!/usr/bin/env python3
"""Writes the list of ROM files the 3DS build reads ahead of the game
(frontend/prefetch_list.h, for NtrFS_Prefetch), in order:
  1. the files of up to 1MB that the desktop harness read in test runs
     (PORT_FSLOG logs), in the order they were first read, so what the game
     needs early comes first;
  2. the other files of up to 1MB the game refers to (the decomp's NARC table
     and paths in its code), smallest first;
  3. the big archives the overworld reads as you go (map blocks, sounds, text,
     models), then the rest, smallest first.
The thread stops when its share of the cache is full, so the order is what
matters. Files the code never names (Diamond and Pearl leftovers in the ROM)
are left out.

usage: gen_prefetch_list.py <romfs dir> <decomp src dir> <out.h> <fslog>...
"""
import os
import re
import sys

romfs, src, out, logs = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]

sizes = {}
for root, _, files in os.walk(romfs):
    for f in files:
        full = os.path.join(root, f)
        sizes[os.path.relpath(full, romfs)] = os.path.getsize(full)

named = set()
pattern = re.compile(r'"/?([A-Za-z0-9_/]+\.[A-Za-z0-9]+)"')
for root, _, files in os.walk(src):
    for f in files:
        if f.endswith((".c", ".h")):
            for m in pattern.finditer(open(os.path.join(root, f), errors="replace").read()):
                if m.group(1) in sizes:
                    named.add(m.group(1))

order = []
for log in logs:
    for line in open(log, errors="replace"):
        m = re.match(r"fs read (\S+) ", line)
        if m and m.group(1) in sizes and sizes[m.group(1)] <= 1 << 20 and m.group(1) not in order:
            order.append(m.group(1))
traced = len(order)

small = sorted((p for p in named if p not in order and sizes[p] <= 1 << 20), key=lambda p: (sizes[p], p))
order += small
big_first = [
    "fielddata/land_data/land_data.narc",
    "data/sound/pl_sound_data.sdat",
    "msgdata/pl_msg.narc",
    "fielddata/build_model/build_model.narc",
    "fielddata/areadata/area_map_tex/map_tex_set.narc",
    "fielddata/areadata/area_build_model/areabm_texset.narc",
    "data/mmodel/mmodel.narc",
]
order += [p for p in big_first if p in sizes and p not in order]
order += sorted((p for p in named if p not in order), key=lambda p: (sizes[p], p))

with open(out, "w") as f:
    f.write("/* Generated by tools/gen_prefetch_list.py: the ROM files the 3DS build reads\n"
            " * ahead of the game (NtrFS_Prefetch), in order: %d files read in test runs,\n"
            " * %d more of up to 1MB, then the big archives. */\n" % (traced, len(small)))
    f.write("static const char *const sPrefetchList[] = {\n")
    total = 0
    for p in order:
        total += sizes[p]
        f.write('    "%s", /* %d KB, %.1f MB in all */\n' % (p, sizes[p] // 1024, total / 1048576))
    f.write("};\n")
print(f"{len(order)} files, {total / 1048576:.1f} MB ({traced} from the logs)")
